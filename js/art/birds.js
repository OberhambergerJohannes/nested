// The crane shares the stork's frame, with a small red crown, a black head and neck and a white
// stripe running from the eye down the back of the neck.
BIRD_T.crane = (() => {
  const t = Object.assign({}, BIRD_T.stork);
  for (const f of ['perch', 'peck', 'fly1', 'fly2']) {
    let crown = true;
    t[f] = BIRD_T.stork[f].map((row) => {
      if (row.includes('c')) {
        if (crown) { crown = false; return row; }
        return row.replace(/c(?=E)/, 'f').replace(/c/g, 'm');
      }
      return row.replace(/n/, 'f');
    });
  }
  return t;
})();
// The crow: a pigeon-sized body with a heavier bill
BIRD_T.crow = (() => {
  const t = Object.assign({}, BIRD_T.pigeon);
  for (const f of ['perch', 'peck', 'fly1', 'fly2']) t[f] = BIRD_T.pigeon[f].map((row) => row.replace(/bb\./, 'bbb'));
  return t;
})();

// Beak shapes for the small template, relative to the first beak pixel
const BEAKS = {
  short: [[0, 0], [1, 0], [0, 1]],
  thin: [[0, 0], [1, 0], [2, 0]],
  finch: [[0, 0], [1, 0], [0, 1], [1, 1]],
  cross: [[0, 0], [1, 0], [2, 1], [0, 1], [1, 2]],
};

function applyBeak(rows, beak) {
  if (!beak || !BEAKS[beak]) return rows;
  let ax = -1, ay = -1;
  for (let y = 0; y < rows.length && ay < 0; y++) { const x = rows[y].indexOf('b'); if (x >= 0) { ax = x; ay = y; } }
  if (ay < 0) return rows;
  const g = rows.map((r) => r.replace(/b/g, '.').split(''));
  for (const [dx, dy] of BEAKS[beak]) {
    const x = ax + dx, y = ay + dy;
    if (y < g.length && x < g[y].length && g[y][x] === '.') g[y][x] = 'b';
  }
  return g.map((r) => r.join(''));
}

// Outline each opaque region with a darkened version of the neighbouring colour.
function shadeOutline(px, outlineHex, amount) {
  const src = px.p.slice(), w = px.w, h = px.h;
  const dark = new Map();
  const get = (x, y) => (x >= 0 && y >= 0 && x < w && y < h) ? src[y * w + x] : 0;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (src[y * w + x] >>> 24) continue;
    let n = 0;
    for (const [dx, dy] of [[0, 1], [0, -1], [-1, 0], [1, 0]]) { const c = get(x + dx, y + dy); if (c >>> 24) { n = c; break; } }
    if (!n) continue;
    let d = dark.get(n);
    if (d === undefined) { d = C(mixHex(toHex(n), outlineHex, amount)); dark.set(n, d); }
    px.p[y * w + x] = d;
  }
  return px;
}

const BIRD_KEYS = 'cnfmEibtrszykwxpaulgh';

function birdPalette(sp) {
  const c = sp.col, pal = {};
  for (const k of BIRD_KEYS) pal[k] = c[k] || c.k;
  pal.E = c.E || '#121218';
  if (!c.i) pal.i = c.f;
  if (!c.g) pal.g = pal.m;
  if (!c.h) pal.h = pal.t;
  return pal;
}

// Crests drawn above the crown, relative to the back of the crown's top row: [dx, dy, region]
const CRESTS = {
  wisp: [[0, -1, 'c'], [-1, -2, 'c'], [-2, -2, 'c'], [-3, -3, 'c']],                                    // lapwing
  fan: [[-1, -1, 'c'], [0, -1, 'c'], [1, -1, 'c'], [2, -1, 'c'], [-1, -2, 'g'], [1, -2, 'g'], [3, -2, 'g'], [0, -2, 'c'], [2, -2, 'c']], // hoopoe
  swept: [[0, -1, 'c'], [-1, -1, 'c'], [-2, 0, 'c'], [-1, -2, 'c']],                                    // waxwing
};
function applyCrest(rows, kind) {
  const shape = CRESTS[kind];
  if (!shape) return rows;
  const g = rows.map((r) => r.split(''));
  const top = g.findIndex((r) => r.includes('c'));
  if (top < 0) return rows;
  const l = g[top].indexOf('c');
  for (const [dx, dy, ch] of shape) {
    const x = l + dx, y = top + dy;
    if (y >= 0 && x >= 0 && x < g[0].length && g[y][x] === '.') g[y][x] = ch;
  }
  return g.map((r) => r.join(''));
}

// Build all frames for one species: {perch, peck, fly1, fly2, hop} plus mirrored *_L
function buildBirdSprites(sp) {
  const T = BIRD_T[sp.body];
  const pal = birdPalette(sp);
  const out = { w: T.w + 2, h: T.h + 2, ax: T.ax + 1, ay: T.ay + 1 };
  for (const name of ['perch', 'peck', 'fly1', 'fly2']) {
    let rows = T[name];
    if (sp.body === 'small' || sp.body === 'longtail') rows = applyBeak(rows, sp.beak);
    if (sp.crest && name !== 'fly2') rows = applyCrest(rows, sp.crest);
    if (sp.tufts && sp.body === 'owl' && (name === 'perch' || name === 'peck')) {
      // ear tufts above the head
      const g = rows.map((r) => r.split(''));
      let top = g.findIndex((r) => r.includes('c'));
      if (top > 0) {
        const xs = g[top].map((ch, i) => (ch === 'c' ? i : -1)).filter((i) => i >= 0);
        const l = xs[0], r = xs[xs.length - 1];
        g[top - 1][l] = 'c'; g[top - 1][r] = 'c';
        if (top > 1) { g[top - 2][Math.max(0, l - 1)] = 'c'; g[top - 2][Math.min(g[0].length - 1, r + 1)] = 'c'; }
        rows = g.map((r) => r.join(''));
      }
    }
    const px = Pix.rows(rows, pal).pad(1, 1, 1, 1);
    shadeOutline(px, sp.col.o || '#1d1a2b', 0.62);
    out[name] = px;
    out[name + '_L'] = px.flipped();
  }
  out.fw = out.fly1.w; out.fh = out.fly1.h;
  // hop: perch lifted 2px without legs
  const hop = new Pix(out.w, out.h);
  const pr = out.perch;
  for (let y = 0; y < pr.h - 2; y++) for (let x = 0; x < pr.w; x++) {
    const c = pr.p[(y + 2) * pr.w + x];
    if (y + 2 >= pr.h - 3) continue;
    hop.p[y * pr.w + x] = c;
  }
  out.hop = hop;
  out.hop_L = hop.flipped();
  return out;
}

// Chicks in the nest: fluffy heads with open, begging gapes
function buildChick(kind) {
  const P = {
    small: { d: '#7a746a', f: '#a8a294', g: '#f6d23a', r: '#e8642a', E: '#202020' },
    big:   { d: '#cfcbc2', f: '#f6f4ee', g: '#3a3a3a', r: '#3a3a3a', E: '#202020' },
    owl:   { d: '#ddd3c4', f: '#fbf8f2', g: '#d8c8b8', r: '#d8c8b8', E: '#202020' },
    duck:  { d: '#6e5a2a', f: '#e6cf5a', g: '#4a3a1a', r: '#4a3a1a', E: '#202020' },
  }[kind];
  const rows = kind === 'duck' ? [
    '..ddd..',
    '.dfEfgg',
    '.ddfff.',
    'dffffd.',
    '.dddd..',
  ] : (kind === 'big' || kind === 'owl') ? [
    '.fff.',
    'fEfEf',
    'ffgff',
    'dfffd',
  ] : [
    'g...g',
    'grrrg',
    '.ggg.',
    'dfffd',
  ];
  return shadeOutline(Pix.rows(rows, P).pad(1, 1, 1, 1), '#2a2420', 0.5);
}

// Eggs: oval mask with a species pattern
const EGG_MASK = ['.###.', '#####', '#####', '#####', '#####', '.###.'];
const EGG_MASK_BIG = ['.####.', '######', '######', '######', '######', '######', '.####.'];
function buildEgg(e, big) {
  const mask = big ? EGG_MASK_BIG : EGG_MASK;
  const px = Pix.rows(mask, { '#': e.c }).pad(1, 1, 1, 1);
  const rnd = artRng('egg' + e.c + e.s + e.p);
  if (e.p === 'scribble') {
    // fine, wandering hairlines (yellowhammers were called "scribble larks")
    for (let i = 0; i < 3; i++) {
      let x = 1 + Math.floor(rnd() * (px.w - 3)), y = 2 + Math.floor(rnd() * (px.h - 4));
      for (let k = 0; k < 3; k++) { if (px.op(x, y)) px.set(x, y, e.s); x += 1; y += rnd() < 0.5 ? 1 : -1; }
    }
  } else if (e.p !== 'none') {
    const n = e.p === 'fine' ? 6 : e.p === 'spots' ? 4 : 3;
    for (let i = 0; i < n; i++) {
      const x = 1 + Math.floor(rnd() * (px.w - 2)), y = 2 + Math.floor(rnd() * (px.h - 3));
      if (px.op(x, y)) {
        px.set(x, y, e.s);
        if (e.p === 'blotch' && px.op(x + 1, y)) px.set(x + 1, y, e.s);
      }
    }
  }
  px.set(2, 2, lighten(e.c, 0.55));
  shadeOutline(px, '#3a3028', 0.55);
  return px;
}
